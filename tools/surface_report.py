"""How wrong was one ATM volatility? SVI surfaces fitted on real chains against the quotes, the error
of pricing a wing at ATM vol, and what early exercise is worth. Writes docs/SURFACE_REPORT.md. Reads
no strategy returns.

    uv run python tools/surface_report.py
"""

from __future__ import annotations

import math
from pathlib import Path

import numpy as np
import pandas as pd

from pusula.data.settings import data_dir
from pusula.options import american, black, surface

ROOT = Path(__file__).resolve().parents[1]
SAMPLE_DATES = 24  # spread evenly over the store
NAMES_PER_DATE = 25
R = 0.03
SEED = 0


def main() -> None:
    store = data_dir() / "optchain"
    rng = np.random.default_rng(SEED)
    parts = sorted(store.glob("part-*.parquet"))
    picks = [parts[int(i)] for i in np.linspace(0, len(parts) - 1, SAMPLE_DATES)]
    fits, errors = [], []
    surfaces = free = calendar_ok = wings = lifted = 0
    premium = []
    for part in picks:
        frame = pd.read_parquet(part)
        day = pd.Timestamp(frame["date"].max())
        chain = frame[frame["date"] == day].copy()
        chain["symbol"] = chain["symbol"].astype(str)
        chain["call_put"] = chain["call_put"].astype(str)
        chain = chain[(chain["expiration"] - chain["date"]).dt.days.between(7, 120)]
        names = chain["symbol"].unique()
        for sym in rng.choice(names, size=min(NAMES_PER_DATE, len(names)), replace=False):
            sub = chain[chain["symbol"] == sym]
            try:
                s = surface.build_surface(sub, str(sym), day, R)
            except surface.SurfaceError:
                continue
            surfaces += 1
            calendar_ok += s.calendar_free
            for f in s.slices:
                fits.append((f.rmse_vol, f.n_quotes, f.butterfly_free, f.T))
                free += f.butterfly_free
                wings += f.butterfly_free_wings
                lifted += f.lifted > 0
                # price the out-of-the-money quotes three ways against their mid
                rows = sub[sub["expiration"] == f.expiry]
                otm = rows[
                    ((rows["call_put"] == "Put") & (rows["strike"] < f.forward * 0.97))
                    | ((rows["call_put"] == "Call") & (rows["strike"] > f.forward * 1.03))
                ]
                atm_vol = float(f.vol(f.forward))
                for _, q in otm.iterrows():
                    if q["bid"] <= 0 or not 0.01 < q["vol"] < 5.0:
                        continue
                    mid = (float(q["bid"]) + float(q["ask"])) / 2.0
                    half = (float(q["ask"]) - float(q["bid"])) / 2.0
                    cp = 1 if q["call_put"] == "Call" else -1
                    K = float(q["strike"])
                    S = f.forward * math.exp(-R * f.T)
                    flat = float(black.price(S, K, f.T, R, 0.0, atm_vol, cp))
                    smile = float(black.price(S, K, f.T, R, 0.0, float(f.vol(K)), cp))
                    errors.append((cp, mid, half, flat, smile))
            first = s.slices[0]
            S = first.forward * math.exp(-R * first.T)
            K = first.forward * 1.1
            v = float(first.vol(K))
            premium.append(american.early_exercise_premium(S, K, first.T, R, 0.0, v, -1) / S)
    fit = np.array(fits, dtype=float)
    err = np.array(errors, dtype=float)
    lines = [
        "# Volatility surfaces on real chains",
        "",
        "Generated by `tools/surface_report.py` from the strike-level store: "
        f"{surfaces} surfaces, {len(fit)} expiries, {len(err):,} out-of-the-money quotes, "
        f"{SAMPLE_DATES} dates across the store. No strategy returns are read.",
        "",
        "| fit | value |",
        "|---|---:|",
        f"| median RMSE at the quotes, volatility points | {np.median(fit[:, 0]) * 100:.2f} |",
        f"| 90th percentile | {np.quantile(fit[:, 0], 0.9) * 100:.2f} |",
        f"| median quotes per expiry | {np.median(fit[:, 1]):.0f} |",
        f"| slices free of butterfly arbitrage, over the quoted range | {free / len(fit):.1%} |",
        f"| the same, out to log-moneyness 1.5 where nothing is quoted | {wings / len(fit):.1%} |",
        f"| surfaces free of calendar arbitrage, over the quoted range | {calendar_ok / surfaces:.1%} |",
        f"| slices lifted to stay above the previous one | {lifted / len(fit):.1%} |",
        "",
        "## What one ATM volatility cost",
        "",
        "Median absolute pricing error against the mid, as a share of the mid, for out-of-the-money "
        "quotes more than 3% from the forward (the error `options.overlay` carried).",
        "",
        "| quotes | n | ATM vol only | SVI smile | half-spread of the quote |",
        "|---|---:|---:|---:|---:|",
    ]
    for name, mask in (("puts", err[:, 0] < 0), ("calls", err[:, 0] > 0)):
        e = err[mask]
        lines.append(
            f"| {name} | {len(e):,} | {np.median(np.abs(e[:, 3] - e[:, 1]) / e[:, 1]):.1%} "
            f"| {np.median(np.abs(e[:, 4] - e[:, 1]) / e[:, 1]):.1%} "
            f"| {np.median(e[:, 2] / e[:, 1]):.1%} |"
        )
    puts = err[err[:, 0] < 0]
    lines += [
        "",
        f"Signed, ATM volatility prices these puts {np.median((puts[:, 3] - puts[:, 1]) / puts[:, 1]):+.1%} "
        "against the mid at the median.",
        "",
        "## Early exercise",
        "",
        f"A put 10% in the money on the nearest expiry: median early-exercise premium "
        f"{np.median(premium) * 1e4:.1f} bp of spot, at {R:.0%} rates and no dividends.",
        "",
    ]
    out = ROOT / "docs" / "SURFACE_REPORT.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(out.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
