"""Post-hoc, exploratory diagnostics for a finished study (NOT part of any gate).

Run after `pusula study run`; writes docs/DIAGNOSTICS.md. Everything here is looked at *after*
the registered results exist and must not be used to tune a registered trial. New ideas found
here become new, separately registered trials.

    uv run python tools/diagnostics.py
"""

from __future__ import annotations

import math
from dataclasses import replace
from pathlib import Path

from pusula.alpha.evaluate import daily_ic, forward_returns, rank_autocorrelation, summarize_ic
from pusula.alpha.signals import REGISTRY, build
from pusula.data.pipeline import research_panel
from pusula.engine.backtest import Backtester
from pusula.live.forward import rf_series
from pusula.research.families import us_equity_v2
from pusula.research.study import make_strategy, window_returns
from pusula.stats import sharpe as S

ROOT = Path(__file__).resolve().parents[1]


def _f(x: float, fmt: str = "{:.3f}") -> str:
    return "n/a" if x is None or not math.isfinite(x) else fmt.format(x)


def main() -> None:
    rd = research_panel()
    p = rd.panel
    mask = p["in_universe"]
    fwd5 = forward_returns(p, 5, 1, price="vwap")
    lines = [
        "# Diagnostics (exploratory, post-hoc: not a gate input)",
        "",
        "Generated by `tools/diagnostics.py` after the registered results were recorded.",
        "",
        "## Signal information coefficients (rank IC vs. next-5-session VWAP-to-VWAP return)",
        "",
        "| signal | dev IC | dev t (NW) | holdout IC | holdout t (NW) | rank autocorr (1d) |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    spec = us_equity_v2()  # research config without the latching kill switch
    dev = (p.date_index(spec.dev[0]), p.asof_index(spec.dev[1]))
    hold = (p.date_index(spec.holdout[0]), p.asof_index(spec.holdout[1]))
    for name in sorted(REGISTRY):
        s = build(name).compute(p)
        ic = daily_ic(s, fwd5, mask)
        d = summarize_ic(ic[dev[0] : dev[1] + 1], horizon=5)
        h = summarize_ic(ic[hold[0] : hold[1] + 1], horizon=5)
        ac = rank_autocorrelation(s[dev[0] : hold[1] + 1], mask[dev[0] : hold[1] + 1])
        lines.append(
            f"| {name} | {_f(d.mean, '{:.4f}')} | {_f(d.t_nw, '{:.2f}')} | {_f(h.mean, '{:.4f}')} | "
            f"{_f(h.t_nw, '{:.2f}')} | {_f(ac, '{:.2f}')} |"
        )

    # Capacity: the composite at increasing capital (costs scale with size through impact + ADV cap)
    rf = rf_series(p)
    trial = next(t for t in spec.trials if t.name == "xs_composite")
    lines += [
        "",
        "## Capacity: `xs_composite` (us-equity-v2 config) at increasing capital (full window, net)",
        "",
        "| capital | Sharpe | ann. return | cost drag / yr | unfilled share |",
        "|---:|---:|---:|---:|---:|",
    ]
    for cap in (1e7, 1e8, 1e9, 5e9):
        cfg = replace(spec.backtest, initial_equity=cap)
        res = Backtester(p, cfg, rf).run(make_strategy(trial, cfg.cost_model))
        r = window_returns(res, spec.dev[0], spec.holdout[1])
        sm = res.summary()
        lines.append(
            f"| ${cap:,.0f} | {_f(S.annualised_sharpe(r), '{:.2f}')} | {_f(S.annualised_return(r), '{:.1%}')} | "
            f"{_f(sm['cost_drag_annual'], '{:.2%}')} | {_f(sm['unfilled'], '{:.1%}')} |"
        )
    out = ROOT / "docs" / "DIAGNOSTICS.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
