"""Data documentation of the fundamentals store (no returns are read; safe before registration).

Writes docs/FUNDAMENTALS_DATA.md: how every membership spell got its CIK, the hand overrides
with their reasons, what stayed unresolved, the event counts and the coverage of each event
field by year for current and for removed index members.

    uv run python tools/fundamentals_report.py
"""

from __future__ import annotations

import json
from pathlib import Path

from pusula.data import fundamentals as F
from pusula.data.cik_overrides import NAME_CONFIRMED
from pusula.data.pipeline import research_panel, with_fundamentals
from pusula.data.settings import data_dir
from pusula.research.families import FUND_HOLD

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    root = data_dir()
    man = json.loads((F.store_dir(root) / "manifest.json").read_text(encoding="utf-8"))
    master = F.read_master(root)
    rd = with_fundamentals(research_panel())
    holds = {"ann_day0": FUND_HOLD["ear"], **{k: v for k, v in FUND_HOLD.items() if k != "ear"}}
    cov = F.coverage(rd.panel, holds)
    lines = [
        "# Fundamentals data (SEC EDGAR, point in time)",
        "",
        "Generated by `tools/fundamentals_report.py` from the store built by "
        "`pusula data fundamentals`. Data quality only: no return is read here.",
        "",
        f"* store digest `{man['digest'][:16]}`, built {man.get('built')}, "
        f"updated {man.get('updated', '-')}",
        f"* {man['securities']} membership spells since {man['since']}, "
        f"{man['resolved']} with a CIK, {man['companies']} companies, "
        f"{man['requests']} requests to data.sec.gov / efts.sec.gov",
        f"* resolution: {man['by_method']}",
        f"* events: {man['events']}",
        "",
        "## How removed members got their CIK",
        "",
        "Wikipedia lists the CIK of current members only. A removed member is searched by "
        "ticker and by four forms of its index name in EDGAR's entity search (a word-prefix "
        "index on *current* names); a candidate is accepted only if every word of the index "
        "name appears in its current or a former EDGAR name (or it still carries the ticker) "
        "**and** it filed 10-K/10-Q reports within 400 days of both ends of the spell (a "
        "successor that started filing later is rejected). Hand overrides are checked the same "
        "way; the four whose index name is a brand EDGAR does not use skip only the name test.",
        "",
        "| security | CIK | method | note |",
        "|---|---|---|---|",
    ]
    special = master[master["method"].isin(["override", "override_unverified", "unresolved"])]
    for _, r in special.sort_values("security_id").iterrows():
        note = str(r["note"]) + (
            " (name confirmed by hand)" if r["security_id"] in NAME_CONFIRMED else ""
        )
        cik = "" if r["cik"] is None or str(r["cik"]) == "<NA>" else str(r["cik"])
        lines.append(f"| {r['security_id']} | {cik} | {r['method']} | {note} |")
    lines += [
        "",
        "## Coverage (share of index-member sessions with a live event)",
        "",
        "Live = an event no older than the signal's hold (sessions): "
        + ", ".join(f"{k} {v}" for k, v in holds.items())
        + ". `current` = still a member at the panel's end, `removed` = left the index. "
        "Accruals and gross profitability exclude financials (SIC 6000-6799) by construction.",
        "",
        "| year | members | member-days | " + " | ".join(holds) + " |",
        "|---|---|---|" + "---|" * len(holds),
    ]
    for _, r in cov.iterrows():
        vals = " | ".join(f"{r[f]:.0%}" for f in holds)
        lines.append(f"| {r['year']} | {r['members']} | {r['member_days']} | {vals} |")
    out = ROOT / "docs" / "FUNDAMENTALS_DATA.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
