"""Data documentation of the FINRA short-volume store (no returns are read; safe before
registration).

Writes docs/SHORTVOL_DATA.md: the store's provenance, the identity check of every member
spell-year (does the FINRA volume read for the security move with its own bars?), the earlier
tickers with their checks, and the coverage of the short-pressure variants.

    uv run python tools/shortvol_report.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from pusula.alpha.signals import build
from pusula.data.pipeline import research_panel
from pusula.data.settings import data_dir
from pusula.data.shortvol import shortvol_fields
from pusula.data.ticker_history import EARLIER_TICKERS

ROOT = Path(__file__).resolve().parents[1]
THRESHOLD = 0.35  # below it a member year is investigated (the rule in data.ticker_history)
# member years below the threshold that were investigated and are the member's own volume
REVIEWED = {
    ("AFL@2016-01-01", 2021): "Aflac has always traded as AFL; no other symbol tracks its bars "
    "(best of all FINRA symbols 0.475, an unrelated stock): a quiet year, not a mismatch",
}
WINDOWS = {"development": ("2019-01-02", "2022-12-30"), "holdout": ("2023-01-03", "2026-10-22")}


def _changes(x: np.ndarray) -> np.ndarray:
    """Daily log changes, clipped: a split moves the adjusted bar volume's level once and is
    then one clipped outlier, not a broken series."""
    with np.errstate(divide="ignore", invalid="ignore"):
        return np.clip(np.diff(np.log(np.where(x > 0, x, np.nan)), axis=0), -1.0, 1.0)


def _corr(a: np.ndarray, b: np.ndarray) -> tuple[float, int]:
    f = np.isfinite(a) & np.isfinite(b)
    if f.sum() < 40:
        return float("nan"), int(f.sum())
    return float(np.corrcoef(a[f], b[f])[0, 1]), int(f.sum())


def main() -> None:
    store = data_dir() / "shortvol"
    meta = json.loads((store / "short_volume.json").read_text(encoding="utf-8"))
    p = research_panel().panel
    fields = shortvol_fields(p, store)
    same_day = np.vstack([fields["finra_volume"][1:], np.full((1, p.n_symbols), np.nan)])
    member = (p["in_universe"] > 0) & (p.dates >= np.datetime64(meta["first"]))[:, None]
    F, B = _changes(same_day), _changes(p["volume"])
    years = pd.DatetimeIndex(p.dates[1:]).year.to_numpy()
    rows = []
    for y in np.unique(years):
        ry = years == y
        for j, sid in enumerate(p.symbols):
            mem = member[1:][ry, j]
            if mem.sum() < 40:
                continue
            c, n = _corr(np.where(mem, F[ry, j], np.nan), np.where(mem, B[ry, j], np.nan))
            rows.append((int(y), sid, c, n, int(mem.sum())))
    ident = pd.DataFrame(rows, columns=["year", "security", "corr", "days", "member_days"])
    low = ident[ident["corr"] < THRESHOLD]
    nodata = ident[ident["days"] == 0]
    few = ident[ident["corr"].isna() & (ident["days"] > 0)]  # under 40 days to correlate
    q = ident["corr"].quantile([0.01, 0.05, 0.25, 0.5]).round(3).to_dict()

    lines = [
        "# Short-sale volume data (FINRA Reg SHO, point in time)",
        "",
        "Generated by `tools/shortvol_report.py` from the store built by "
        "`pusula data short-volume`. Data quality only: no return is read here.",
        "",
        f"* source `{meta['source']}`, sessions {meta['first']} to {meta['last']}, "
        f"{meta['rows']:,} rows, {meta['symbols']:,} symbols, sessions without a file: "
        f"{meta['missing'] or 'none'}",
        f"* per-file SHA-256 chain `{meta['chain_sha256'][:16]}`",
        "* a session's file is used from the next session's close (FINRA publishes it after "
        "the close, observed 17:16 ET)",
        "",
        "## Identity: is it the member's own volume?",
        "",
        "FINRA names a stock by the ticker it had that day; a security id carries today's "
        "ticker. For every member year the correlation of daily log-volume changes between "
        "the FINRA volume read for the security and its own bars is measured (clipped "
        "changes, so a split in the adjusted bar volume does not break it). Same company: "
        "typically 0.6-0.9. A year below "
        f"{THRESHOLD} was investigated; the earlier tickers found that way are in "
        "`src/pusula/data/ticker_history.py`.",
        "",
        f"* member years measured: {len(ident)}; quantiles of the correlation: {q}",
        f"* member years with no FINRA rows under the security's tickers: {len(nodata)}",
        f"* member years with rows on too few days to measure (under 40): {len(few)}",
        f"* member years below {THRESHOLD}: {len(low)}",
        "",
    ]
    if len(low):
        lines += [
            "| year | security | correlation | days | review |",
            "|---|---|---:|---:|---|",
        ]
        for _, r in low.sort_values(["security", "year"]).iterrows():
            note = REVIEWED.get((r["security"], r["year"]), "**not reviewed**")
            lines.append(
                f"| {r['year']} | {r['security']} | {r['corr']:.3f} | {r['days']} | {note} |"
            )
        lines.append("")
    if len(nodata):
        lines += ["| year | security without rows | member days |", "|---|---|---:|"]
        for _, r in nodata.sort_values(["security", "year"]).iterrows():
            lines.append(f"| {r['year']} | {r['security']} | {r['member_days']} |")
        lines.append("")

    lines += [
        "## Earlier tickers",
        "",
        "| security | earlier ticker | until (first session of the next) |",
        "|---|---|---|",
    ]
    for sid, segs in sorted(EARLIER_TICKERS.items()):
        for tick, until in segs:
            lines.append(f"| {sid} | {tick} | {until} |")
    lines.append("")

    dates = pd.DatetimeIndex(p.dates)
    panel = p.with_fields(**fields)
    lines += [
        "## Coverage (share of index-member sessions with a score)",
        "",
        "| variant | " + " | ".join(WINDOWS) + " |",
        "|---|" + "---:|" * len(WINDOWS),
    ]
    for fast, slow in ((5, 60), (20, 120)):
        ok = np.isfinite(build("short_pressure", fast=fast, slow=slow).compute(panel))
        cells = []
        for a, b in WINDOWS.values():
            rows_w = (dates >= a) & (dates <= b)
            m = member[rows_w]
            cells.append(f"{(ok[rows_w] & m).sum() / m.sum():.1%}")
        lines.append(f"| short_pressure {fast}/{slow} | " + " | ".join(cells) + " |")
    out = ROOT / "docs" / "SHORTVOL_DATA.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
